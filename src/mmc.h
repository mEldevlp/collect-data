// Консоль MMC (gpedit.msc, lusrmgr.msc): запуск с возвратом вида консоли пользователя, навигация по
// дереву (SysTreeView32), список результатов (SysListView32) и окна свойств его строк.
//
// Дерево и строки списка читаются через специальные возможности Windows (MSAA, acc.h): узлы и строки
// сами сообщают свои названия и сами дают себя выделить - в память процесса mmc.exe ничего не пишется
// и не читается. MSAA работает и при разной разрядности процессов, поэтому отдельная сборка под
// разрядность mmc тут не нужна.
#ifndef SCREENS_MMC_H
#define SCREENS_MMC_H

#include <windows.h>
#include "names.h"

#define MMC_FRAME_CLASS L"MMCMainFrame"     // главное окно mmc.exe

typedef struct
{
    HWND  frame;                // главное окно консоли
    HWND  tree;                 // дерево консоли (левая панель); NULL - не найдено
    HWND  list;                 // список результатов (правая панель); заполняется в mmc_wait_result_list
    void *tree_accessible;      // IAccessible клиентской области дерева (храним как void*, чтобы не
                                // тянуть oleacc.h в заголовок); NULL - дерево не прочитать
} MMC;

// Открыть консоль <system32>\<msc_name>.msc в mmc.exe и дождаться окна MMCMainFrame (окно запоминается
// для закрытия). MMC при закрытии сохраняет вид консоли в профиль пользователя
// (%APPDATA%\Microsoft\MMC\<msc_name>: положение окна, ширина столбцов) - после закрытия этот файл
// возвращается как был (или удаляется, если его не было). NULL - окно не появилось.
HWND mmc_open_console(const WCHAR *msc_name, const WCHAR *log_name, DWORD timeout_ms);

// Подключиться к дереву консоли: загрузить oleacc, найти SysTreeView32, дождаться корневого узла
// (до timeout_ms) и получить его IAccessible. FALSE - причина в журнале; mmc_detach вызывать всегда.
BOOL mmc_attach(MMC *mmc, HWND frame, DWORD timeout_ms);
void mmc_detach(MMC *mmc);

// Пройти путь от корня консоли, раскрывая узлы, и выделить последний (MMC покажет его содержимое
// в правой панели). FALSE - узел не найден (в журнал - видимые узлы) или не раскрылся
// за expand_timeout_ms.
BOOL mmc_select_path(MMC *mmc, const NAMES_PATH *path, DWORD expand_timeout_ms);

// MMC 3.0 (Vista+): спрятать область действий справа ("Действия"), чтобы она не отнимала место у списка
// результатов, - кнопкой панели инструментов (ищется через MSAA по словарю names.c). Вид консоли после
// закрытия всё равно возвращается как был. На XP (MMC 2.0) области нет - ничего не делает.
void mmc_hide_action_pane(MMC *mmc);

// Список результатов (правая панель): найти его и дождаться, пока число строк перестанет расти
// (число строк - в журнал). FALSE - списка нет или он пуст.
BOOL mmc_wait_result_list(MMC *mmc, DWORD timeout_ms);

// Столбцы списка политик (gpedit): название и значение видны целиком; не влезают оба - значение
// (второй столбец) показываем целиком, столбец названия сужаем.
void mmc_fit_value_column(MMC *mmc);

// Первые text_columns столбцов - по ширине текста и заголовка (видны целиком), следующему столбцу -
// оставшееся место (длинный текст в нём обрежется многоточием). Не влезают - первый столбец всё равно
// целиком, остальные текстовые сужаются, чтобы следующему досталось хотя бы немного места. Для списка
// пользователей lusrmgr: "Имя" и "Полное имя" целиком, "Описание" - что останется.
void mmc_fit_text_columns(MMC *mmc, int text_columns);

// Открыть окно свойств строки списка результатов с названием item_name (целиком, без учёта регистра):
// строка находится и выделяется через MSAA, затем Enter в списке (запасной путь - двойной щелчок
// через MSAA); ждать новое окно свойств (#32770 с вкладками) процесса консоли до timeout_ms на каждый
// способ. Окно запоминается для закрытия под именем log_name. NULL - строки нет или окно не открылось.
HWND mmc_open_item_properties(MMC *mmc, const WCHAR *item_name, const WCHAR *log_name, DWORD timeout_ms);

// /dump: дочерние окна консоли, видимые узлы дерева и строки списка результатов - в журнал.
void mmc_dump(MMC *mmc);

#endif
